// Generates the rule reference (content/docs/rules/) from rules/**/*.toml,
// so the docs always match the catalog the core ships. Run by `predev` and
// `prebuild`; the output folder is git-ignored.
import { mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "smol-toml";

const here = path.dirname(fileURLToPath(import.meta.url));
const rulesDir = path.resolve(here, "../../rules");
const outDir = path.resolve(here, "../content/docs/rules");

const SEVERITY = ["critical", "high", "medium", "low", "info"];
const SERVICES = [
  { key: "firebase.firestore", slug: "firestore", title: "Cloud Firestore" },
  { key: "firebase.database", slug: "realtime-database", title: "Realtime Database" },
  { key: "firebase.storage", slug: "storage", title: "Cloud Storage" },
  { key: "firebase.auth", slug: "authentication", title: "Authentication" },
  { key: "firebase.functions", slug: "functions", title: "Cloud Functions" },
  { key: "generic", slug: "generic", title: "Generic rules" },
];
const TIER = {
  local: "Local: one call, runs in the SDK",
  window: "Window: one session, runs on the backend (and in the SDK in dev mode)",
  aggregate: "Aggregate: all sessions of a project, runs on the backend",
};

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = path.join(dir, name);
    if (statSync(full).isDirectory()) return walk(full);
    return name.endsWith(".toml") ? [full] : [];
  });
}

/** Escapes MDX-special characters outside inline code spans. */
function prose(text) {
  return String(text ?? "")
    .trim()
    .split(/(`[^`]*`)/g)
    .map((part) => (part.startsWith("`") ? part : part.replace(/[{}<>]/g, (c) => `\\${c}`)))
    .join("");
}

function oneLine(text) {
  return prose(text).replace(/\s*\n\s*/g, " ").replace(/\|/g, "\\|");
}

function serviceOf(rule) {
  return rule.id.startsWith("generic/") ? "generic" : rule.id.split("/")[0];
}

function anchor(rule) {
  return rule.id.split("/")[1];
}

function statusNote(rule) {
  if (rule.status === "planned") return "Planned: defined in the catalog, no detector yet, disabled by default.";
  if (rule.status === "beta") return "Beta: the detector may still change.";
  if (rule.default_enabled === false) return "Disabled by default.";
  return "";
}

function renderRule(rule) {
  const lines = [`## ${rule.title}`, "", `\`${rule.id}\``, ""];
  lines.push("| Severity | Category | Evaluation | Status |", "|---|---|---|---|");
  lines.push(`| ${rule.severity} | ${rule.category} | ${rule.evaluation} | ${rule.status} |`, "");
  const note = statusNote(rule);
  if (note) lines.push(`<Callout type="warn">${note}</Callout>`, "");
  lines.push(prose(rule.summary), "", prose(rule.description), "");
  lines.push("**Fix.** " + prose(rule.fix), "");
  const params = rule.params ? Object.entries(rule.params) : [];
  if (params.length > 0) {
    lines.push("| Parameter | Default |", "|---|---|");
    for (const [name, value] of params) lines.push(`| \`${name}\` | \`${value}\` |`);
    lines.push("");
  }
  for (const example of rule.examples ?? []) {
    const lang = example.lang ?? "ts";
    if (example.bad) lines.push("Costly:", "", "```" + lang, example.bad.trim(), "```", "");
    if (example.good) lines.push("Cheaper:", "", "```" + lang, example.good.trim(), "```", "");
  }
  const links = (rule.docs ?? []).map((url) => `[${url.replace(/^https:\/\//, "")}](${url})`);
  if (links.length > 0) lines.push("Firebase docs: " + links.join(", "), "");
  return lines.join("\n");
}

function sortRules(rules) {
  return rules.sort(
    (a, b) => SEVERITY.indexOf(a.severity) - SEVERITY.indexOf(b.severity) || a.id.localeCompare(b.id),
  );
}

const rules = walk(rulesDir).map((file) => parse(readFileSync(file, "utf8")));
rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });

const pages = [];
for (const service of SERVICES) {
  const list = sortRules(rules.filter((rule) => serviceOf(rule) === service.key));
  if (list.length === 0) continue;
  pages.push(service.slug);
  const active = list.filter((rule) => rule.status !== "planned").length;
  const body = [
    "---",
    `title: ${service.title}`,
    `description: ${list.length} rules, ${active} active.`,
    "---",
    "",
    `{/* Generated by docs/scripts/gen-rules.mjs from rules/. Do not edit. */}`,
    "",
    "| Rule | Severity | Evaluation |",
    "|---|---|---|",
    ...list.map((rule) => `| [${oneLine(rule.title)}](#${anchor(rule)}) | ${rule.severity} | ${rule.evaluation} |`),
    "",
    ...list.map((rule) => `<a id="${anchor(rule)}" />\n\n${renderRule(rule)}`),
  ].join("\n");
  writeFileSync(path.join(outDir, `${service.slug}.mdx`), body);
}

const total = rules.length;
const active = rules.filter((rule) => rule.status !== "planned").length;
const counts = SEVERITY.map((s) => `${rules.filter((r) => r.severity === s && r.status !== "planned").length} ${s}`).join(", ");
const index = [
  "---",
  "title: Rule reference",
  `description: All ${total} rules in the catalog, ${active} of them active.`,
  "---",
  "",
  `{/* Generated by docs/scripts/gen-rules.mjs from rules/. Do not edit. */}`,
  "",
  `Active rules by severity: ${counts}.`,
  "",
  "Severity is ranked by cost impact. `critical` means cost grows without bound with data size or traffic, `high` is a large multiplier (roughly 5x or more), `medium` is measurable waste on a hot path, `low` is minor waste or latency only, and `info` is an observation.",
  "",
  ...Object.entries(TIER).map(([, text]) => `- ${text}`),
  "",
  "| Rule | Service | Severity | Evaluation | Status |",
  "|---|---|---|---|---|",
  ...sortRules([...rules]).map((rule) => {
    const service = SERVICES.find((s) => s.key === serviceOf(rule));
    return `| [\`${rule.id}\`](/docs/rules/${service.slug}#${anchor(rule)}) | ${service.title} | ${rule.severity} | ${rule.evaluation} | ${rule.status} |`;
  }),
  "",
].join("\n");
writeFileSync(path.join(outDir, "index.mdx"), index);
writeFileSync(
  path.join(outDir, "meta.json"),
  JSON.stringify({ title: "Rule reference", pages: ["index", ...pages] }, null, 2) + "\n",
);
console.log(`rules: ${total} (${active} active) -> ${path.relative(process.cwd(), outDir)}`);
